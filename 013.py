# Given two numbers, use comparison operators to print whether the first is greater, smaller, or equal — all using boolean expressions, without an if statement.

num1 = int(input("Enter First Number : "))
num2 = int(input("Enter Second Number : "))

print("First Number is greater : ", num1 > num2)
print("First Number is smaller : ", num1 < num2)
print("Both are Equal : ", num1 == num2)